#!/usr/bin/env python3
"""Generate Swift colour tokens from docs/design/tokens.json (M09).

The iOS app builds its colour sets from the same file, so this keeps the Mac in the same palette.
Writes Backline/UI/Palette.swift:

  BacklineColors        one value per token, in the light, dark and high-contrast sets
  BacklineColors.of()   the set for a look
  stemColor(hue, dark:) a part colour from the OKLCH hue, at the token lightness

Usage: scripts/gen_palette.py [--check]
"""
from __future__ import annotations
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "docs" / "design" / "tokens.json"
OUT = ROOT / "Backline" / "UI" / "Palette.swift"


def swift_color(hex_color: str, alpha: float | None) -> str:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    if alpha is None:
        return f"Color(hex: 0x{r:02X}{g:02X}{b:02X})"
    return f"Color(hex: 0x{r:02X}{g:02X}{b:02X}, alpha: {alpha:g})"


def camel(name: str) -> str:
    return name[:1].lower() + name[1:]


def value(token: dict, mode: str, hc: bool) -> str:
    hcset = token.get("hc") or {}
    if hc and mode in hcset:
        v = hcset[mode]
        if isinstance(v, dict):
            return swift_color(v["light"] if mode == "light" else v["dark"], v.get("a"))
        return swift_color(v, token.get("a"))
    return swift_color(token[mode], token.get("a"))


def main() -> int:
    data = json.loads(TOKENS.read_text())
    tokens: dict[str, dict] = data["tokens"]
    names = list(tokens)
    lightness = data["stemLightness"]

    lines: list[str] = []
    lines.append("// GENERATED by scripts/gen_palette.py from docs/design/tokens.json - do not edit by hand.")
    lines.append("import SwiftUI")
    lines.append("")
    lines.append("/// One complete set of Backline colours (the Soundcheck palette). Values are fixed per look: the")
    lines.append("/// Mac never uses a dynamic `Color` for them, so a snapshot, a sheet and the window always agree.")
    lines.append("struct BacklineColors: Equatable {")
    for n in names:
        lines.append(f"    var {camel(n)}: Color")
    lines.append("")
    lines.append("    static let light = BacklineColors(")
    for n in names:
        lines.append(f"        {camel(n)}: {value(tokens[n], 'light', False)},")
    lines.append("    )")
    lines.append("    static let dark = BacklineColors(")
    for n in names:
        lines.append(f"        {camel(n)}: {value(tokens[n], 'dark', False)},")
    lines.append("    )")
    lines.append("    static let lightHc = BacklineColors(")
    for n in names:
        lines.append(f"        {camel(n)}: {value(tokens[n], 'light', True)},")
    lines.append("    )")
    lines.append("    static let darkHc = BacklineColors(")
    for n in names:
        lines.append(f"        {camel(n)}: {value(tokens[n], 'dark', True)},")
    lines.append("    )")
    lines.append("")
    lines.append("    static func of(dark: Bool, highContrast: Bool = false) -> BacklineColors {")
    lines.append("        switch (dark, highContrast) {")
    lines.append("        case (true, true): return .darkHc")
    lines.append("        case (true, false): return .dark")
    lines.append("        case (false, true): return .lightHc")
    lines.append("        case (false, false): return .light")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// A part's colour from its OKLCH hue, at the token lightness for this look.")
    lines.append(f"    func stem(_ hue: Double) -> Color {{ Self.stemColor(hue, dark: self == .dark || self == .darkHc) }}")
    lines.append("")
    lines.append(f"    /// OKLCH to sRGB at the design's stem lightness (0.{int(lightness['light']*100):02d} on paper, "
                 f"0.{int(lightness['dark']*100):02d} in the dark) and chroma {lightness['chroma']}.")
    lines.append("    static func stemColor(_ hue: Double, dark: Bool) -> Color {")
    lines.append(f"        let l = dark ? {lightness['dark']} : {lightness['light']}")
    lines.append(f"        let (r, g, b) = oklchToSRGB(l: l, c: {lightness['chroma']}, h: hue)")
    lines.append("        return Color(.sRGB, red: r, green: g, blue: b)")
    lines.append("    }")
    lines.append("")
    lines.append("    static func oklchToSRGB(l: Double, c: Double, h: Double) -> (Double, Double, Double) {")
    lines.append("        let hr = h * .pi / 180")
    lines.append("        let a = c * cos(hr), b = c * sin(hr)")
    lines.append("        let l_ = l + 0.3963377774 * a + 0.2158037573 * b")
    lines.append("        let m_ = l - 0.1055613458 * a - 0.0638541728 * b")
    lines.append("        let s_ = l - 0.0894841775 * a - 1.2914855480 * b")
    lines.append("        let L = l_ * l_ * l_, M = m_ * m_ * m_, S = s_ * s_ * s_")
    lines.append("        let rl = 4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S")
    lines.append("        let gl = -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S")
    lines.append("        let bl = -0.0041960863 * L - 0.7034186147 * M + 1.7076147010 * S")
    lines.append("        func gamma(_ x: Double) -> Double {")
    lines.append("            let v = max(0, min(1, x))")
    lines.append("            return v <= 0.0031308 ? 12.92 * v : 1.055 * pow(v, 1 / 2.4) - 0.055")
    lines.append("        }")
    lines.append("        return (gamma(rl), gamma(gl), gamma(bl))")
    lines.append("    }")
    lines.append("}")
    text = "\n".join(lines) + "\n"

    if "--check" in sys.argv:
        same = OUT.is_file() and OUT.read_text() == text
        print("palette: up to date" if same else "palette: OUT OF DATE - run scripts/gen_palette.py")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(names)} tokens x 4 sets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
